def get_epilogue(ending_type: str) -> str:
    """
    Get the epilogue for a specific ending

    Args:
        ending_type: Type of ending (miracle, disappearance, redchurch, cor_manifestation)

    Returns:
        Epilogue text
    """
    epilogues = {
        "miracle": EPILOGUE_MIRACLE,
        "disappearance": EPILOGUE_DISAPPEARANCE,
        "redchurch": EPILOGUE_REDCHURCH_CANON,
        "cor_manifestation": EPILOGUE_COR_TAKEOVER,
        "total_collapse": EPILOGUE_TOTAL_COLLAPSE,
        "dce_overrun": EPILOGUE_DCE_OVERRUN,
    }

    return epilogues.get(ending_type, "")


def get_secret_ending(archetype_counts: dict) -> str:
    """
    Get secret ending if player committed heavily to one archetype

    Args:
        archetype_counts: Dict of archetype choice counts

    Returns:
        Secret ending text if triggered, empty string otherwise
    """
    total_choices = sum(archetype_counts.values())

    if total_choices == 0:
        return ""

    # Calculate percentages
    percentages = {
        archetype: (count / total_choices) * 100
        for archetype, count in archetype_counts.items()
    }

    # Check for 70% threshold
    for archetype, percentage in percentages.items():
        if percentage >= 70.0:
            if archetype == "witness":
                return SECRET_WITNESS
            elif archetype == "trickster":
                return SECRET_TRICKSTER
            elif archetype == "devourer":
                return SECRET_DEVOURER

    return ""  # No secret ending triggered
