def get_death_screen(character_name: str, death_type: str = "generic") -> str:
    """
    Get the appropriate death screen for a character

    Args:
        character_name: Name of the character who died
        death_type: Type of death (generic, pressure, scar_collapse, dyad_collapse)

    Returns:
        Formatted death screen text
    """
    # Character-specific screens
    character_screens = {
        "Maeve": DEATH_SCREEN_MAEVE,
        "Kit": DEATH_SCREEN_KIT,
        "Yuul": DEATH_SCREEN_YUUL_NO_BOND,  # Default Yuul screen
        "Rielle": DEATH_SCREEN_RIELLE,
        "Daniel": DEATH_SCREEN_DANIEL,
        "Farris": DEATH_SCREEN_FARRIS,
    }

    # Use character-specific screen if available, otherwise generic
    if character_name in character_screens:
        return character_screens[character_name]

    # Generic screens with name substitution
    generic_screens = {
        "generic": DEATH_SCREEN_GENERIC,
        "pressure": DEATH_SCREEN_PRESSURE_OVERLOAD,
        "scar_collapse": DEATH_SCREEN_SCAR_COLLAPSE,
        "dyad_collapse": DEATH_SCREEN_DYAD_COLLAPSE,
    }

    template = generic_screens.get(death_type, DEATH_SCREEN_GENERIC)
    return template.format(character_name=character_name)


def get_yuul_death_screen(has_sacred_bond: bool, at_wound_site: bool) -> str:
    """
    Get the appropriate Yuul death screen based on circumstances

    Args:
        has_sacred_bond: Whether Yuul had a sacred bond when she hit C=0
        at_wound_site: Whether dissolution happened at Redchurch or similar

    Returns:
        Formatted death screen text
    """
    if at_wound_site:
        return DEATH_SCREEN_YUUL_WOUND_SITE
    elif has_sacred_bond:
        return DEATH_SCREEN_YUUL_BOND_FAILED
    else:
        return DEATH_SCREEN_YUUL_NO_BOND


def get_game_over_screen(game_over_type: str) -> str:
    """
    Get the appropriate game over screen for catastrophic failures

    Args:
        game_over_type: Type of game over (mass_dissolution, protagonist_lost, trine_collapsed)

    Returns:
        Formatted game over screen text
    """
    screens = {
        "mass_dissolution": GAME_OVER_MASS_DISSOLUTION,
        "protagonist_lost": GAME_OVER_PROTAGONIST_LOST,
        "trine_collapsed": GAME_OVER_TRINE_COLLAPSED,
    }

    return screens.get(game_over_type, GAME_OVER_MASS_DISSOLUTION)
